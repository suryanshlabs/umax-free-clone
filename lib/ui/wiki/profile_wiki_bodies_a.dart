String mewingBody() => '''
Tongue posture — what people call "mewing" — is the habit of resting the whole
tongue against the palate with lips sealed, teeth lightly together, and breathing
through the nose.

What the evidence supports
- It is anatomically reasonable: the tongue is a large muscle and a resting
  position on the palate is closer to the developmental norm than mouth-breathing
  with the tongue low.
- For someone who mouth-breathes habitually, switching to nasal breathing and a
  tongue-up posture can improve the resting look of the lower face in motion, by
  changing how the lips and chin sit.
- It costs nothing and is unlikely to hurt, so it is a fair habit to try.

What it does not support
- Claims that "mewing reshapes the adult jaw" are not backed by good clinical
  evidence. Bone that has finished growing does not remodel under resting tongue
  pressure at the magnitudes and durations people describe.
- The effect on bone is strongest in children whose growth is still active; in
  adults the realistic change is in resting posture, not structure.

Practical notes
- Do it as resting posture, not as a forceful exercise. Pressing hard for hours
  can strain the area and does not improve the result.
- If you cannot comfortably keep the tongue on the palate, that is often a sign
  of nasal obstruction or a dental/orthodontic issue worth a clinician's look.
- Keep the measurement honest: if you want to see whether anything changed,
  re-scan the front face under the same light and compare with your saved scans,
  not with a memory of how you looked.
''';

String swallowBody() => '''
Swallowing mechanics matter because a habitual tongue-thrust swallow — where the
tongue pushes forward against the teeth on each swallow — can, over years, affect
the position of the teeth and the resting shape of the lower face.

What the evidence supports
- Tongue-thrust swallowing is a real pattern dentists and orthodontists screen for.
- Repeated forward tongue pressure at the teeth is associated with the lower
  incisors leaning forward over time; the detail is in the dental literature, not
  the cosmetic one.
- Soft tissue resting posture changes how the lower face reads in photos of the
  same person.

What it does not support
- A single swallowing pattern is not a lever for changing facial bone in adults on
  a useful timeline.
- There is no convincing evidence that manual "swallow correction drills" change
  the angle this app measures.

Practical notes
- A normal swallow finishes with the tongue up against the palate and the lips
  together.
- If you notice your tongue consistently pushing forward, the practical step is to
  be aware of it during meals and to mention it at a dental check.
- For the app's purposes, the relevant comparison is "same person, same capture
  conditions" — not one swallow versus another.
''';

String nasalBody() => '''
Nasal breathing is the default healthy resting mode for most people, and a mouth
open at rest tends to pull the lower face down and forward in a way that shows up
in photos.

What the evidence supports
- Chronic mouth breathing is associated with a longer, lower-looking face in
  growing children, and with dry mouth and dental issues in adults.
- Nasal breathing is the physiologically normal route; the nose warms, filters and
  humidifies the air.
- Poor nasal airflow can make it genuinely hard to keep the lips sealed and the
  tongue up, so fixing the breathing often helps the posture that sits underneath
  any facial habit.

What it does not support
- The app cannot tell whether your mouth is open at rest, and a single photo is
  not a diagnostic test for airway obstruction.
- Nasal breathing will not move the gonial angle on its own.

Practical notes
- If you mouth-breathe because the nose is genuinely blocked (deviated septum,
  allergies, chronic congestion), the honest fix is to have a clinician look at
  the cause.
- If you can breathe through your nose but habitually keep your mouth open, simply
  noticing and closing it at rest is the intervention.
- For glow-up purposes, nasal breathing is part of "look more relaxed and upright",
  which benefits any photo more than any one number.
''';

String sleepBody() => '''
Sleeping posture is one of the most-cited environmental contributors to facial
asymmetry, mostly because sustained pressure from a pillow or hand on one side of
the face can, over a long time, affect soft tissue and to a lesser extent the
skin and underlying contours.

What the evidence supports
- Sustained unilateral pressure is a plausible soft-tissue contributor to mild
  asymmetry — the mechanism is straightforward, even if the magnitude in any one
  person is small.
- Observational associations exist between side-sleeping and mild asymmetry; the
  data are not high-quality experimental evidence.
- Switching sides or sleeping on your back removes one variable at essentially no
  cost.

What it does not support
- There is no strong proof that changing sleep posture will reshape an adult face
  in a measurable way within weeks.
- The effect, where it exists, is slow and soft-tissue-level; bone is not the
- For the app's purpose, sleep posture is one of the "capture-adjacent habits"
  that can move a reading a little.

Practical notes
- If you wake up more puffy on one side, that side of the face tends to read
  slightly different the next morning. A re-scan after a normal, even night is a
  better signal.
- Back-sleeping is the most neutral position for symmetry. Side-sleeping is fine
  if you rotate sides; it is the years on one side that add up.
- A pillow that keeps the head level is better than a very high or very flat one
  that tilts the chin toward the chest.
''';
