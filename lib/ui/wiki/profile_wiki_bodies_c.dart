String sodiumBody() => '''
Sodium and water retention affect facial puffiness the next morning, which rounds
the jaw and can shift a scan a few points. It is real but temporary, and it reverses
with a normal night and a lower-sodium evening.

What the evidence supports
- High sodium intake raises water retention; facial puffiness is one of the visible
  manifestations.
- Short sleep increases facial fluid retention and puffiness.
- Alcohol often worsens both fluid retention and sleep quality, so a salty, alcohol-
  heavy evening is the worst case for the next-morning face.

What it does not support
- Cutting sodium will not change the jawbone or the fat layer; it changes the fluid
  sitting over them for a day or two.
- This is cosmetic and temporary, so it should not be read as progress.

Practical notes
- For a cleaner photo the next morning: lower sodium the evening before, hydrate, get
  a normal night, and avoid a late alcohol-heavy meal.
- If you are more puffy on one side after sleeping on it, that is fluid plus pressure,
  not a permanent change.
- Use the app's re-scan-after-a-normal-night advice before concluding anything from a
  soft morning reading.
''';

String dietBody() => '''
Dietary guidelines for facial definition are really the same as the general guidelines
for a healthy body composition, because the face reflects the whole: fat, fluid, sleep
and the capture conditions.

What the evidence supports
- Adequate protein supports preserving muscle and shape while in a deficit.
- A sustainable calorie deficit is the route to lower body fat generally, including the
  face for people who lose fat there.
- Vegetables, fiber and steady meals support the same slow, sustainable pattern that
  actually changes body composition.
- Sodium and alcohol drive short-term fluid retention; a normal evening helps the next
  morning's photo.

What it does not support
- No specific food makes the jawline sharper directly.
- Supplement "de-bloating" claims are mostly marketing; the honest fixes are the boring
  ones above.

Practical notes
- Keep the boring habits boring and consistent: a modest deficit, enough protein,
  resistance training, consistent sleep, steady sodium.
- For the app, the dietary side shows up as a trend over weeks, not a single scan.
- If the number moves a little after a better night and a lower-sodium evening, that is
  fluid, not a structural change — and it is still useful as photo hygiene.
''';

String skinBody() => '''
Skin routine by archetype is a small library of framings rather than a single plan: the
same habits (cleanse, moisturize, sunscreen) matter for everyone, but the emphasis
changes with skin type and with what the person actually wants to improve.

What the evidence supports
- Daily sunscreen is the single best-evidenced intervention for how facial skin ages,
  and it pays off over years rather than weeks.
- Cleansing and basic moisturizing are low-risk and genuinely helpful for comfort and
  barrier health.
- Acne-prone skin responds to a small number of well-evidenced topical approaches; the
  same ingredient is not right for every person.
- Dry, sensitive and oily skin benefit from different emphases: hydrating and barrier-
  supporting for dry/sensitive, lighter and less occlusive for oily.

What it does not support
- No routine will change the underlying bone or the jaw angle. Skin is about surface
  look, which changes how a face reads but not what the app measures.
- Aggressive routines often hurt the barrier and make things worse; less is frequently
  more.

Practical notes
- The archetype that matters most is "what bothers the person", because skin goals are
  personal: smoothness, fewer breakouts, less redness, less visible oil, fewer dark
  marks.
- A useful framining: one gentle cleanser, one moisturizer that suits the skin type,
  sunscreen every day, and a single targeted active for the specific concern, introduced
  slowly.
- If breakouts are persistent, painful or scarring, a clinician or dermatologist is the
  right next step; acne can have causes that routine alone will not touch.
''';

String scheduleBody() => '''
Routine schedules keep the good habits doing their job without turning skincare into a
homework assignment. The schedule below is a skeleton, not a rigid rule; pick the
cadence that fits the person's skin and life.

A simple weekly frame
- Every morning: gentle cleanse (or just water if the skin is dry and there is no
  overnight product to remove), moisturizer if needed, sunscreen.
- Every evening: cleanse to remove dirt, oil and any actives or makeup, then moisturize.
- A few times a week, depending on skin tolerance: a single targeted active (for example
  a retinoid for texture, or a salicylic acid for oily/acne-prone skin), introduced one at
  a time and slowly.

How to think about the cadence
- Start slower than you think. A new active every night is the fastest route to a damaged
  barrier and a worse result.
- Watch for irritation; if the skin stings, gets redder or drier, back off the active and
  focus on barrier for a bit.
- Consistency beats intensity. A modest routine done most days is more useful than an
  aggressive routine done irregularly.

Practical notes
- Keep it comparable: if you want the app's photos to mean anything, photograph on the
  same routine cadence so the skin is in similar condition each time.
- Sleep and stress affect skin as much as products do; they are part of the routine even
  though they are not in the bottle.
- If a concern is not improving over a few months, or is worsening, that is a clinician
  conversation, not a routine tweak.
''';

String hairBody() => '''
Hairstyles for facial proportions are about framing: the hairline, volume and part can
change how the face reads more than any other single non-medical lever, because the
hairline actually bounds the upper third of the face.

What the evidence supports
- The upper third of the face is bounded by the hairline, so hair is the easiest third
  to move visually.
- Volume at the crown lengthens the upper third; a flatter, closer cut at the top
  shortens it.
- A part, fringe and styling can balance or emphasize the perceived width of the forehead
  and jaw.
- Grooming the brows sets where the upper third ends for most people, so brow shape and
  tidiness matter alongside hair.

What it does not support
- A hairstyle does not change the bone; it changes the perceived shape by framing it.
- There is no universal "best hairstyle for your face": the useful question is "what
  balance do I want", and the answer is personal.

Practical notes
- If your lower third dominates, volume up top is the cheapest rebalance.
- If your forehead reads large, a fringe or softer part can balance it.
- If your jaw reads wide, keep the sides and back cleaner rather than building volume at
  the jaw corners, which visually widens the lower face.
- Keep the look consistent between scans if you want the measurement comparison to be
  meaningful; different hair is a different photo.
- The same framing logic applies to facial hair: a short beard adds visual length to the
  lower third, while a clean neckline sharpens the edge without adding width at the jaw.
''';
