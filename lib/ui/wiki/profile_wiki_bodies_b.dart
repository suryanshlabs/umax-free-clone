String chewBody() => '''
Chewing on one side more than the other loads one masseter and one temporomandibular
joint more than the other, and dental research links habitual one-sided chewing to
measurable differences in the lower face over time.

What the evidence supports
- The masseter is a muscle; muscles respond to load. Chewing more on one side can
  hypertrophy that side more than the other.
- Dental and orthodontic literature associates unilateral chewing with asymmetry in
  the lower face and in the bite.
- Deliberately starting meals on the less-used side is the entire intervention, and
  it costs nothing.

What it does not support
- Acute changes are unlikely; any visible effect on the jawline from this takes time
  and is mainly soft tissue.
- Chewing gum hard on both sides can grow both masseters, which can actually widen
  the lower face — so "chew more" is not automatically the right move for every
  look.

Practical notes
- For symmetry, the habit is: start each meal on the side you use least, and notice
  whether you drift back to a favorite side.
- For jawline definition, decide what look you want before you train the masseter.
  A wider, fuller jaw is a deliberate aesthetic choice for some people.
- If chewing is painful or uneven, mention it at a dental check — pain is a signal,
  not a glow-up exercise.
''';

String muscleBody() => '''
Muscle imbalances in the face are usually about the masseter, the platysma and the
neck posture chain rather than the tiny upper-face muscles.

What the evidence supports
- Forward head posture flattens the angle between jaw and neck, which is one of the
  largest single differences between a "soft" and a "defined" jaw in a photo.
- Chronic unilateral habits — chewing, holding a phone between shoulder and ear,
  leaning on one hand — build or relax muscle unevenly.
- Improving general posture and reducing one-sided habits can change the resting look
  of the lower face, mostly through soft tissue and position rather than bone.

What it does not support
- There is no quick route to a meaningfully different muscle balance through facial
  exercises alone, and "face yoga" claims are not well supported in the peer-reviewed
  literature for structural change.
- Muscle balance changes are subtle and mostly cosmetic.

Practical notes
- The highest-value posture fix is: stand or sit tall, pull the shoulders back, and
  keep the chin slightly tucked so the jaw-necks angle is cleaner.
- For the app, the relevant comparison is the front face under the same light — not
  a "before and after" taken minutes apart with different posture.
- If one side of the jaw is clearly smaller or tighter for a long time, mention it
  at a clinician's visit; persistent imbalance can have causes other than habit.
''';

String fatBody() => '''
Body composition is part of the picture, but it is not something this app measures
or advises on. The face mesh only describes geometry: where landmarks sit in one
photo. Height, weight, age and BMI live in the separate BMI Calculator and are
never read by the facial analysis.

What the geometry does and does not show
- Fat sits over the mandible and under the chin, so the soft-tissue outline can
  differ between two people with the same bone structure. A frontal photo cannot
  separate the two.
- Where fat is stored is largely genetic, and it changes slowly. A single scan
  cannot tell you whether a jaw-border difference is bone, muscle, fat or fluid.
- Body weight and BMI are not part of any facial measurement in this app, and a
  BMI result never changes a face reading in either direction.

What the evidence does not support
- Spot reduction: you cannot choose to lose fat from the jaw only.
- The idea that one particular jaw shape is healthy or unhealthy. Jaw geometry
  is not a health marker.

Practical notes
- If you want to track body composition, use the BMI tool as a rough screening
  number and read its limitations; it deliberately gives no targets or diet plan.
- If a change in your face or jaw is sudden, painful, or one-sided, that is a
  clinical question and belongs with a doctor, not a scan.
''';

String trackBody() => '''
Tracking facial definition over time is useful if you do it honestly: the same face,
same light, same distance, same time of day, compared side by side rather than from
memory.

What the evidence supports
- Day-to-day variation in a facial reading is dominated by fluid, lighting, camera
  distance and angle, and sleep — not by structural change.
- A real trend is a month or more of similar conditions showing movement; one
  exceptional photo is a snapshot.
- The app's progress comparison is designed exactly for this: two scans of you under
  comparable conditions, with the capture notes visible so you can read the context.

What it does not support
- "Tracked daily" is not the same as "trending". A single day's number can move a few
  points for reasons that have nothing to do with your face.
- The app's numbers are geometric estimates from one 2D photo; they are not a clinical
  measurement of fat, bone or muscle.

Practical notes
- Pick a consistent capture setup: same room, same window light, phone vertical at
  eye level, 50–70 cm away, neutral face, hair off the forehead.
- Re-scan weekly rather than daily for meaningful comparison.
- Read the three measurements, not just the overall number: an overall point or two
  of movement inside one metric is often indistinguishable from capture noise.
''';
